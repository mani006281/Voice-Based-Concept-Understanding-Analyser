from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer
)

from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.pagesizes import A4

from datetime import datetime
from pathlib import Path
from html import escape
from uuid import uuid4


# Get the project root directory
BASE_DIR = Path(__file__).resolve().parent.parent

# Directory to store generated PDF reports
REPORTS_DIR = BASE_DIR / "reports"


def generate_pdf(student_name, concept, transcript, similarity, feedback):

    # Create reports directory if it does not exist
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)

    # Generate a unique PDF filename
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    unique_id = uuid4().hex[:8]

    filename = REPORTS_DIR / f"evaluation_{timestamp}_{unique_id}.pdf"

    # Create PDF document
    doc = SimpleDocTemplate(
        str(filename),
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    # Load styles
    styles = getSampleStyleSheet()

    # PDF content
    story = []

    # Report title
    story.append(
        Paragraph(
            "Voice Based Concept Understanding Analyser",
            styles["Title"]
        )
    )

    story.append(Spacer(1, 20))

    # Student name
    story.append(
        Paragraph(
            f"<b>Student Name:</b> {escape(str(student_name))}",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 10))

    # Concept
    story.append(
        Paragraph(
            f"<b>Concept:</b> {escape(str(concept))}",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 10))

    # Date
    story.append(
        Paragraph(
            f"<b>Date:</b> {datetime.now().strftime('%d-%m-%Y %H:%M')}",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 20))

    # Transcript section
    story.append(
        Paragraph(
            "Transcript",
            styles["Heading2"]
        )
    )

    story.append(
        Paragraph(
            escape(str(transcript)).replace("\n", "<br/>"),
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 20))

    # Semantic similarity section
    story.append(
        Paragraph(
            "Semantic Similarity",
            styles["Heading2"]
        )
    )

    story.append(
        Paragraph(
            f"{float(similarity):.2f}%",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 20))

    # Gemini AI feedback section
    story.append(
        Paragraph(
            "Gemini AI Feedback",
            styles["Heading2"]
        )
    )

    story.append(
        Paragraph(
            escape(str(feedback)).replace("\n", "<br/>"),
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 20))

    # Footer
    story.append(
        Paragraph(
            "Generated by Voice Based Concept Understanding Analyser",
            styles["Italic"]
        )
    )

    # Generate PDF
    doc.build(story)

    # Return the generated PDF path
    return str(filename)